"""ORSTAC Lab: exact risk ranking of Deriv Bot strategies on synthetic volatility indices.

Volatility indices (R_*, 1HZ*V) are generated by a random number generator, so indicators cannot change
the probability of a contract. A bot's long-run outcome then depends only on:
  1. the contract's true win probability (exact for digits; ~0.5 for rise/fall),
  2. the real payout Deriv quotes for it,
  3. the stake progression after wins and losses,
  4. the stop-loss / take-profit it enforces.
The Lab prices each contract with the public API, simulates every bot under one published protocol and
gives it an ORSTAC Score. No bot has a positive expectation here: the ranking is about safety, not profit.
"""

from __future__ import annotations

import random
from dataclasses import asdict, dataclass, field

from .risk import prob_losing_streak

# ---- Protocol (published with the ranking) -------------------------------------------------------------
BANKROLL_UNITS = 100.0          # base stake = 1 unit = 1% of the bankroll (ORSTAC 1% rule)
SESSION_CONTRACTS = 1000        # contracts per simulated session
SIMULATIONS = 2000              # sessions per configuration
STOP_LOSS_UNITS = 20.0          # applied when the bot has a session loss limit (20% of bankroll)
TAKE_PROFIT_UNITS = 10.0        # applied when the bot has a profit target (10% of bankroll)
DEFAULT_MARTINGALE = 2.0        # when the multiplier is set at runtime
DEFAULT_SOFT = 1.5
SOROS_LEVELS = 3                # wins reinvested before resetting
ADMISSION_MAX_RUIN = 0.01       # admitted only below 1% ruin in a 1,000-contract session
ADMISSION_MAX_EDGE_PCT = 5.0    # and only on contracts whose house edge is at most 5%
SEED = 20261109

SYNTHETIC_PREFIXES = ("R_", "1HZ")
DIGIT_TYPES = {"DIGITDIFF", "DIGITMATCH", "DIGITEVEN", "DIGITODD", "DIGITOVER", "DIGITUNDER"}
RISEFALL_TYPES = {"CALL", "PUT"}
RISEFALL_TRADES = {"risefall", "callput", None}


def exact_win_probability(contract_type: str, prediction: float | None = None) -> float | None:
    """True win probability of a contract on an RNG volatility index, or None when it is not exact.

    Last digits are uniform on 0-9. Rise/fall is a symmetric random walk: 0.5 is an upper bound
    (an exact tie loses), so the Lab is slightly generous to rise/fall bots.
    """
    ct = (contract_type or "").upper()
    if ct == "DIGITDIFF":
        return 0.9
    if ct == "DIGITMATCH":
        return 0.1
    if ct in ("DIGITEVEN", "DIGITODD"):
        return 0.5
    if ct in ("DIGITOVER", "DIGITUNDER"):
        if prediction is None or not float(prediction).is_integer() or not 0 <= prediction <= 9:
            return None
        d = int(prediction)
        p = (9 - d) / 10 if ct == "DIGITOVER" else d / 10
        return p if 0 < p < 1 else None
    if ct in RISEFALL_TYPES:
        return 0.5
    return None


@dataclass(frozen=True)
class ContractKey:
    symbol: str
    contract_type: str
    duration: int
    duration_unit: str
    barrier: str | None

    def id(self) -> str:
        b = f":{self.barrier}" if self.barrier is not None else ""
        return f"{self.symbol}:{self.contract_type}:{self.duration}{self.duration_unit}{b}"


def contract_key(audit) -> tuple[ContractKey | None, list[str], str | None]:
    """(key, assumptions, reason_if_not_modeled) for a BotAudit."""
    notes: list[str] = []
    ct = (audit.contract_side or "").upper()
    if ct in RISEFALL_TYPES and audit.trade_type not in RISEFALL_TRADES:
        return None, notes, f"{audit.trade_type} contracts depend on a barrier; not modeled exactly"
    if ct not in DIGIT_TYPES and ct not in RISEFALL_TYPES:
        return None, notes, f"contract {ct or 'unknown'} is not modeled exactly"
    symbol = audit.symbol or ""
    if not symbol.startswith(SYNTHETIC_PREFIXES):
        return None, notes, f"market {symbol or 'unknown'} is not an RNG volatility index"
    if exact_win_probability(ct, audit.prediction) is None:
        return None, notes, "digit prediction is set at runtime; probability depends on it"
    is_digit = ct in DIGIT_TYPES
    unit = audit.duration_unit or "t"
    dur = audit.duration
    if unit != "t" or dur is None or not float(dur).is_integer() or not 1 <= dur <= 10:
        dur = 1 if is_digit else 5
        unit = "t"
        notes.append(f"duration set at runtime or outside 1-10 ticks; priced at {dur} ticks")
    barrier = None
    if ct in ("DIGITOVER", "DIGITUNDER"):
        barrier = str(int(audit.prediction))
    elif ct in ("DIGITDIFF", "DIGITMATCH"):
        barrier = str(int(audit.prediction)) if audit.prediction is not None else "5"
        if audit.prediction is None:
            notes.append("digit chosen at runtime; all digits have the same probability and payout")
    return ContractKey(symbol, ct, int(dur), unit, barrier), notes, None


async def fetch_payouts(keys, client, pause: float = 0.5) -> dict[str, dict]:
    """Net payout ratio per contract (profit per 1 unit staked), priced on the public API."""
    import asyncio

    table: dict[str, dict] = {}
    for k in sorted(set(keys), key=lambda x: x.id()):
        for attempt in range(6):
            try:
                q = await client.proposal(k.symbol, k.contract_type, k.duration, k.duration_unit, stake=10.0,
                                          barrier=k.barrier)
                table[k.id()] = {"net_payout_ratio": q["net_payout_ratio"], "payout_per_10": q["payout"]}
                break
            except Exception as exc:  # pricing errors are recorded, not fatal
                table[k.id()] = {"error": str(exc)[:200]}
                if "RateLimit" not in str(exc):
                    break
                await asyncio.sleep(10 * (attempt + 1))  # the public API throttles bursts of proposals
        await asyncio.sleep(pause)
    return table


# ---- Simulation ------------------------------------------------------------------------------------------
@dataclass(frozen=True)
class StrategyConfig:
    win_prob: float
    net_ratio: float
    progression: str            # none | martingale | soft | soros
    multiplier: float
    stop_loss: bool
    take_profit: bool


@dataclass
class LabMetrics:
    ruin_probability: float
    stop_loss_rate: float
    take_profit_rate: float
    mean_session_result_units: float
    expected_loss_per_100_contracts_units: float
    median_contracts_played: int
    p95_max_drawdown_pct: float
    p99_losing_streak: int
    house_edge_pct: float

    def to_dict(self) -> dict:
        return asdict(self)


def simulate(cfg: StrategyConfig, simulations: int = SIMULATIONS, n_contracts: int = SESSION_CONTRACTS,
             seed: int = SEED) -> LabMetrics:
    rng = random.Random(seed)
    ruined = stopped = profited = 0
    results, played, drawdowns = [], [], []
    turnover_total = 0.0
    for _ in range(simulations):
        bal, peak, max_dd, step, soros, stake = BANKROLL_UNITS, BANKROLL_UNITS, 0.0, 0, 0, 1.0
        n = 0
        for n in range(1, n_contracts + 1):
            if stake > bal + 1e-9:
                ruined += 1
                n -= 1
                break
            turnover_total += stake
            if rng.random() < cfg.win_prob:
                profit = stake * cfg.net_ratio
                bal += profit
                step = 0
                if cfg.progression == "soros" and soros < SOROS_LEVELS:
                    soros += 1
                    stake = stake + profit
                else:
                    soros, stake = 0, 1.0
            else:
                bal -= stake
                soros = 0
                if cfg.progression in ("martingale", "soft"):
                    step += 1
                    stake = cfg.multiplier ** step
                else:
                    stake = 1.0
            if bal > peak:
                peak = bal
            dd = (peak - bal) / peak
            if dd > max_dd:
                max_dd = dd
            pnl = bal - BANKROLL_UNITS
            if cfg.stop_loss and pnl <= -STOP_LOSS_UNITS:
                stopped += 1
                break
            if cfg.take_profit and pnl >= TAKE_PROFIT_UNITS:
                profited += 1
                break
        results.append(bal - BANKROLL_UNITS)
        played.append(n)
        drawdowns.append(max_dd)
    drawdowns.sort()
    played.sort()
    total_played = sum(played) or 1
    loss_streak = _p99_streak(1 - cfg.win_prob, n_contracts)
    return LabMetrics(
        ruin_probability=round(ruined / simulations, 4),
        stop_loss_rate=round(stopped / simulations, 4),
        take_profit_rate=round(profited / simulations, 4),
        mean_session_result_units=round(sum(results) / simulations, 2),
        expected_loss_per_100_contracts_units=round(-100 * sum(results) / total_played, 2),
        median_contracts_played=played[len(played) // 2],
        p95_max_drawdown_pct=round(100 * drawdowns[int(0.95 * (len(drawdowns) - 1))], 1),
        p99_losing_streak=loss_streak,
        house_edge_pct=round(100 * (1 - cfg.win_prob * (1 + cfg.net_ratio)), 2),
    )


def _p99_streak(loss_prob: float, n: int) -> int:
    """Smallest losing streak L that happens with probability <= 1% in n contracts."""
    for L in range(1, n + 1):
        if prob_losing_streak(L, n, loss_prob) <= 0.01:
            return L
    return n


PROGRESSION_POINTS = {"none": 1.0, "soros": 0.6, "soft": 0.4, "martingale": 0.0}


def orstac_score(m: LabMetrics, cfg: StrategyConfig) -> int:
    """0-100. 50 survival + 20 stop-loss + 15 progression + 15 contract cost (lower house edge)."""
    survival = 50 * (1 - m.ruin_probability)
    stop = 20 if cfg.stop_loss else 0
    prog = 15 * PROGRESSION_POINTS.get(cfg.progression, 0.0)
    cost = 15 * max(0.0, 1 - max(0.0, m.house_edge_pct) / 10)
    return int(round(survival + stop + prog + cost))


def admitted(m: LabMetrics, cfg: StrategyConfig) -> tuple[bool, list[str]]:
    why = []
    if m.ruin_probability >= ADMISSION_MAX_RUIN:
        why.append(f"ruin probability {m.ruin_probability:.1%} in {SESSION_CONTRACTS} contracts")
    if not cfg.stop_loss:
        why.append("no session stop-loss")
    if cfg.progression == "martingale":
        why.append("martingale progression")
    if m.house_edge_pct > ADMISSION_MAX_EDGE_PCT:
        why.append(f"contract house edge {m.house_edge_pct:.1f}% (max {ADMISSION_MAX_EDGE_PCT:g}%)")
    return not why, why


@dataclass
class LabEntry:
    file: str
    contract: str
    win_probability: float
    net_payout_ratio: float
    progression: str
    multiplier: float
    stop_loss: bool
    take_profit: bool
    score: int
    admitted: bool
    rejected_because: list[str]
    metrics: dict
    assumptions: list[str] = field(default_factory=list)


def strategy_config(audit, win_prob: float, net_ratio: float) -> tuple[StrategyConfig, list[str]]:
    notes = []
    prog = audit.progression or "none"
    mult = audit.progression_multiplier
    if prog == "martingale" and not mult:
        mult = DEFAULT_MARTINGALE
        notes.append(f"martingale factor set at runtime; simulated at x{DEFAULT_MARTINGALE:g}")
    elif prog == "soft" and not mult:
        mult = DEFAULT_SOFT
        notes.append(f"soft factor set at runtime; simulated at x{DEFAULT_SOFT:g}")
    elif prog == "soros":
        notes.append(f"soros simulated with {SOROS_LEVELS} reinvested wins")
    mult = float(mult or 1.0)
    return StrategyConfig(round(win_prob, 4), round(net_ratio, 4), prog, round(mult, 3),
                          bool(audit.has_loss_limit), bool(audit.has_profit_target)), notes


def protocol() -> dict:
    return {
        "bankroll_units": BANKROLL_UNITS, "base_stake_units": 1.0, "session_contracts": SESSION_CONTRACTS,
        "simulations_per_config": SIMULATIONS, "stop_loss_units_if_bot_has_one": STOP_LOSS_UNITS,
        "take_profit_units_if_bot_has_one": TAKE_PROFIT_UNITS, "default_martingale": DEFAULT_MARTINGALE,
        "default_soft": DEFAULT_SOFT, "soros_levels": SOROS_LEVELS, "seed": SEED,
        "admission": f"ruin < {ADMISSION_MAX_RUIN:.0%}, has a session stop-loss, no martingale, "
                     f"contract house edge <= {ADMISSION_MAX_EDGE_PCT:g}%",
        "score": "50 x (1 - ruin) + 20 stop-loss + 15 x progression (none 1, soros 0.6, soft 0.4, "
                 "martingale 0) + 15 x (1 - house edge / 10%)",
        "ruin": "the balance cannot pay the next stake required by the bot",
        "markets": "RNG volatility indices only (R_*, 1HZ*V); rise/fall at p=0.5 is an upper bound",
    }


def rank(entries: list[LabEntry]) -> list[LabEntry]:
    return sorted(entries, key=lambda e: (-e.score, e.metrics["expected_loss_per_100_contracts_units"], e.file))


def run_lab(folder: str, simulations: int = SIMULATIONS, payouts: dict | None = None) -> dict:
    """Audit every XML in `folder`, price the contracts, simulate each distinct strategy once, rank."""
    from pathlib import Path

    from .deriv_api import DerivPublicClient, run
    from .xml_audit import audit_file

    root = Path(folder)
    audits = [audit_file(f) for f in sorted(root.rglob("*.xml"))]
    parsed = [a for a in audits if a.parsed]
    keyed, skipped = [], {}
    for a in parsed:
        key, notes, reason = contract_key(a)
        if key is None:
            skipped[reason] = skipped.get(reason, 0) + 1
        else:
            keyed.append((a, key, notes))
    if payouts is None:
        async def _price():
            async with DerivPublicClient() as c:
                return await fetch_payouts([k for _, k, _ in keyed], c)
        payouts = run(_price())
    cache: dict[StrategyConfig, LabMetrics] = {}
    entries = []
    for a, key, notes in keyed:
        quote = payouts.get(key.id(), {})
        if "net_payout_ratio" not in quote:
            skipped["contract could not be priced"] = skipped.get("contract could not be priced", 0) + 1
            continue
        p = exact_win_probability(key.contract_type, None if key.barrier is None else float(key.barrier))
        cfg, cfg_notes = strategy_config(a, p, quote["net_payout_ratio"])
        if cfg not in cache:
            cache[cfg] = simulate(cfg, simulations=simulations)
        m = cache[cfg]
        ok, why = admitted(m, cfg)
        entries.append(LabEntry(
            file=Path(a.file).relative_to(root).as_posix(), contract=key.id(), win_probability=cfg.win_prob,
            net_payout_ratio=cfg.net_ratio, progression=cfg.progression, multiplier=cfg.multiplier,
            stop_loss=cfg.stop_loss, take_profit=cfg.take_profit, score=orstac_score(m, cfg), admitted=ok,
            rejected_because=why, metrics=m.to_dict(), assumptions=notes + cfg_notes))
    ranked = rank(entries)
    return {
        "protocol": protocol(),
        "files": len(audits), "parsed": len(parsed), "modeled": len(ranked),
        "admitted": sum(e.admitted for e in ranked), "distinct_strategies_simulated": len(cache),
        "not_modeled": dict(sorted(skipped.items(), key=lambda kv: -kv[1])),
        "payouts": payouts,
        "ranking": [asdict(e) for e in ranked],
    }
